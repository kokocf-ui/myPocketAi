import assert from 'node:assert/strict';
import {THEORY_ENTRIES,searchTheory,theorySubjects} from './education_theory.mjs';
const math=THEORY_ENTRIES.filter(e=>e.subject==='math');
const topics=['arithmetic','algebra','geometry','trigonometry','functions','measurement','statistics','linear-algebra','analysis','differential','discrete'];
assert.equal(math.length,211);
assert.deepEqual(theorySubjects().map(x=>x.count),[211,19,268]);
assert.deepEqual([...new Set(math.map(e=>e.topic))].sort(),[...topics].sort());
for(const t of topics)assert.ok(math.filter(e=>e.topic===t).length>=9,t+' has a populated library');
assert.deepEqual([...new Set(math.map(e=>e.level))].sort(),['advanced','beginner','intermediate','medium'].sort());
assert.equal(new Set(THEORY_ENTRIES.map(e=>e.id)).size,THEORY_ENTRIES.length);
assert.ok(THEORY_ENTRIES.every(e=>e.id&&e.title&&e.statement&&e.subject&&e.level));
assert.ok(math.every(e=>e.topic&&e.formula));
assert.deepEqual(searchTheory('',{subject:'math'}),[],'no default examples appear before typing');
assert.equal(searchTheory('p',{subject:'math',level:'beginner',limit:4}).length,4,'index from first letter');
assert.ok(searchTheory('pita',{subject:'math',level:'beginner'}).some(e=>e.title==='Pitagora'));
assert.equal(searchTheory('teorema lui Pitagora',{subject:'math'})[0].title,'Pitagora');
assert.equal(searchTheory('legea lui ohm',{subject:'physics'})[0].title,'Legea lui Ohm');
assert.equal(searchTheory('conservarea masei',{subject:'chemistry'})[0].title,'Legea conservării masei');
assert.equal(searchTheory('legea inertiei',{subject:'physics'})[0].title,'Prima lege a lui Newton');
assert.equal(searchTheory('derivata',{subject:'math',level:'beginner'}).length,0);
assert.ok(searchTheory('derivata',{subject:'math',level:'intermediate'}).length>0);
assert.equal(searchTheory('teorema lui Green',{subject:'math',level:'intermediate'}).length,0,'advanced theory stays advanced');
assert.ok(searchTheory('teorema lui Green',{subject:'math',level:'advanced'}).length>0);
assert.equal(searchTheory('pitagora',{subject:'chemistry'}).length,0);
assert.equal(searchTheory('p',{subject:'math',limit:4}).length,4);
console.log('PASS mathematics catalog: 211 mathematical entries across 11 branches, three levels, indexed typeahead, 38 science entries');
