export function physicsUniversityRoutes(country){
 const code=String(country||'').toUpperCase();
 if(!Object.prototype.hasOwnProperty.call(PHYSICS_UNIVERSITY_PROFILES,code))return [];
 const profile=PHYSICS_UNIVERSITY_PROFILES[code];
 const ref=profile?.verifiedExample;
 const general=years=>({
  id:'general-'+years,years,
  ro:years+' ani · program orientativ'+(code.startsWith('GB-')?'':(' · model '+(years*60)+' ECTS')),
  en:years+' years · advisory route'+(code.startsWith('GB-')?'':(' · '+(years*60)+'-ECTS model')),
  source:PHYSICS_UNIVERSITY_EHEA_SOURCE,verified:false,
  provenanceRo:'Model comparativ european de '+years+' ani, nu confirmare de programă pentru această țară.',
  provenanceEn:'European '+years+'-year comparison model; not a verified curriculum for this country.'
 });
 const routes=ref?[{
  id:'example-'+ref.years,years:ref.years,
  ro:ref.years+' ani · exemplu universitar verificat',
  en:ref.years+' years · documented university example',
  source:ref.source,verified:true,
  provenanceRo:'Exemplu documentat: '+ref.institutionRo+'. Distribuția disciplinelor rămâne orientativă.',
  provenanceEn:'Documented example: '+ref.institutionEn+'. Course allocation remains advisory.'
 }]:[];
 for(const ex of profile?.specialExamples||[]){
  if(ex.years===ref?.years)continue;
  routes.push({id:'special-'+ex.years,years:ex.years,ro:ex.years+' ani · '+ex.ro,
   en:ex.years+' years · '+ex.en,source:ex.source,verified:true,
   provenanceRo:'Exemplu documentat: '+ex.ro+'. Nu este o licență standard identică în toate universitățile.',
   provenanceEn:'Documented example: '+ex.en+'. Not a universally identical national Physics degree.'});
 }
 for(const years of [3,4]){
  if(!routes.some(r=>r.years===years))routes.push(general(years));
 }
 return routes;
}
export function physicsUniversityYears(country,routeId){
 const routes=physicsUniversityRoutes(country);
 const route=routes.find(r=>r.id===routeId)||routes[0];
 return route?Array.from({length:route.years},(_,i)=>({
  id:'univ-'+(i+1),ro:'Anul universitar '+(i+1),
  en:'University year '+(i+1),universityYear:i+1,routeId:route.id
 })):[];
}
export function physicsUniversityRoute(country,routeId){
 const routes=physicsUniversityRoutes(country);
 return routes.find(r=>r.id===routeId)||routes[0]||null;
}
