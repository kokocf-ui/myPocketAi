#!/usr/bin/env node
// Generates or verifies decoupled curriculum pack JSON assets in ./public/packs/
// AND writes ./curriculum_pack_manifest.mjs (tiny ~1 KB client/worker index, so
// esbuild never bundles the raw curriculum lesson modules into the Worker).
// Usage:
//   node scripts/build_curriculum_packs.mjs           # build/sync packs + manifest
//   node scripts/build_curriculum_packs.mjs --verify  # CI check that disk matches source

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { curriculumPackAssetName } from '../curriculum_pack_protocol.mjs';
import {
  ALL_DECOUPLED_CURRICULUM_PACKS,
  CURRICULUM_REMOTE_PACK_KEYS,
  CURRICULUM_PACK_BUNDLE_VERSION,
  HUNGARY_CLIENT_GRADE_META
} from '../curriculum_pack_catalog.mjs';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packsDir = path.join(rootDir, 'public', 'packs');
const manifestPath = path.join(rootDir, 'curriculum_pack_manifest.mjs');
const verifyOnly = process.argv.includes('--verify');

await fs.mkdir(packsDir, { recursive: true });

const expectedFiles = new Map();
let totalBytes = 0;

for (const pack of ALL_DECOUPLED_CURRICULUM_PACKS) {
  const fileName = await curriculumPackAssetName(pack.subject, pack.country, pack.grade);
  if (!fileName) {
    throw new Error(`Invalid pack tuple: ${pack.subject}/${pack.country}/${pack.grade}`);
  }
  const serialized = JSON.stringify({
    ...pack,
    packVersion: CURRICULUM_PACK_BUNDLE_VERSION
  });
  expectedFiles.set(fileName, serialized);
  totalBytes += Buffer.byteLength(serialized);
}

const expectedManifest =
  `// Auto-generated by scripts/build_curriculum_packs.mjs — do not edit manually.\n` +
  `// Keeps heavy curriculum packs out of the Cloudflare Worker JS bundle.\n` +
  `export const CURRICULUM_PACK_BUNDLE_VERSION = ${JSON.stringify(CURRICULUM_PACK_BUNDLE_VERSION)};\n` +
  `export const CURRICULUM_REMOTE_PACK_KEYS = Object.freeze(${JSON.stringify(CURRICULUM_REMOTE_PACK_KEYS)});\n` +
  `export const HUNGARY_CLIENT_GRADE_META = Object.freeze(${JSON.stringify(HUNGARY_CLIENT_GRADE_META)});\n`;

const existingEntries = await fs.readdir(packsDir).catch(() => []);
const existingPackFiles = existingEntries.filter(f => /^p-[0-9a-f]{24}\.json$/.test(f));

if (verifyOnly) {
  const actualManifest = await fs.readFile(manifestPath, 'utf8').catch(() => null);
  if (actualManifest !== expectedManifest) {
    console.error('FAIL: Out-of-sync curriculum_pack_manifest.mjs. Run: node scripts/build_curriculum_packs.mjs');
    process.exit(1);
  }
  for (const [fileName, expectedContent] of expectedFiles.entries()) {
    const fullPath = path.join(packsDir, fileName);
    const actual = await fs.readFile(fullPath, 'utf8').catch(() => null);
    if (actual !== expectedContent) {
      console.error(`FAIL: Out-of-sync or missing curriculum pack ${fileName}. Run: node scripts/build_curriculum_packs.mjs`);
      process.exit(1);
    }
  }
  for (const fileName of existingPackFiles) {
    if (!expectedFiles.has(fileName)) {
      console.error(`FAIL: Stale curriculum pack ${fileName} in public/packs/. Run: node scripts/build_curriculum_packs.mjs`);
      process.exit(1);
    }
  }
  console.log(`PASS curriculum packs verified: ${expectedFiles.size} packs (${(totalBytes / 1024).toFixed(1)} KB), version=${CURRICULUM_PACK_BUNDLE_VERSION}`);
  process.exit(0);
}

await fs.writeFile(manifestPath, expectedManifest, 'utf8');
for (const [fileName, content] of expectedFiles.entries()) {
  await fs.writeFile(path.join(packsDir, fileName), content, 'utf8');
}
for (const fileName of existingPackFiles) {
  if (!expectedFiles.has(fileName)) {
    await fs.unlink(path.join(packsDir, fileName));
  }
}

console.log(`Built ${expectedFiles.size} decoupled curriculum packs in public/packs/ (${(totalBytes / 1024).toFixed(1)} KB, version=${CURRICULUM_PACK_BUNDLE_VERSION})`);
