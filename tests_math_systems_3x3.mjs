import assert from 'node:assert/strict';
import vm from 'node:vm';
import frontend from './index.js';
const html=await(await frontend.fetch(new Request('https://fixture/'))).text();
const script=[...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)][0]?.[1];
assert.ok(script,'embedded math script');
new vm.Script(script);
const a=script.indexOf('function mathMatrix3Det(');
const b=script.indexOf('function mathAlgebraEngines(',a);
assert.ok(a>0&&b>a,'3x3 functions before registry');
const api=vm.runInNewContext(script.slice(a,b)+'\n({det:mathMatrix3Det,parse:mathSystem3x3,solve:mathSystem3x3Solution,method:mathSystem3x3Method,graph:mathSystem3x3Graph})',
 {state:{language:'ro'},learningLabel:(ro,en)=>ro,mathLinearNotation:()=>({number:n=>String(Object.is(n,-0)?0:n).replace('-','−')})});
const example='x+y+z=6\n2x-y+z=3\nx+2y-z=2';
const m=api.parse(example);
assert.ok(m,'recognize 3 lines');
assert.equal(m.kind,'unique');
assert.deepEqual([m.values.x,m.values.y,m.values.z],[1,2,3]);
assert.equal(m.determinant,7);
assert.equal(m.detX,7);
assert.equal(m.detY,14);
assert.equal(m.detZ,21);
const sol=api.solve(example);
assert.equal(sol.steps.length,4);
assert.equal(sol.steps[3].verificationSteps.length,3,'verify all equations');
assert.match(sol.conclusion,/x = 1, y = 2, z = 3/);
assert.ok(api.method(example).rules.length>=5);
assert.match(api.graph(example).conclusion,/Intersecția celor trei plane: \(1; 2; 3\)/);
assert.equal(api.parse('x+y+z=3\n2x+2y+2z=6\nx-y=0').kind,'dependent');
assert.equal(api.parse('x+y+z=3\nx+y+z=4\nx-y=0').kind,'inconsistent');
assert.equal(api.parse('x+y+z=3\nx+y+z=3\nx-y=0').kind,'dependent');
assert.equal(api.parse('x+y+z=3\nx+y=2'),null,'do not treat two lines as 3x3');
assert.equal(api.parse('x^2+y+z=3\nx+y+z=4\nx-y=0'),null,'reject nonlinear');
assert.equal(api.parse('x*y+z=3\nx+y+z=4\nx-y=0'),null,'reject variable multiplication');
assert.equal(api.parse('x+y+z=3\nx+y+z=4\nx-y=0\nz=1'),null,'reject extra line');
assert.equal(api.det([[1,2,3],[0,1,4],[5,6,0]]),1);
assert.equal(api.det([[1,2,3],[1,2,3],[1,0,2]]),0);
assert.equal(api.det([[1,2],[3,4]]),null);
assert.ok(script.includes("id:'linear-system-3x3'"));
console.log('PASS 3x3 matrices and systems: unique, inconsistent, dependent, proof, 3D disclosure');
