import assert from "node:assert/strict";
import {buildWorldNewsDiscoveryPlan,selectNewsPublisherDiverseSources,describeNewsPublishers} from "./news_discovery.mjs";
const y=buildWorldNewsDiscoveryPlan("Ce evenimente importante s-au întâmplat ieri în lume?",{publicationDay:"2026-11-04"});
assert.equal(y.broadWorld,true);assert.equal(y.gdeltQueries.length,2);
assert.match(y.wireQuery,/Reuters/);assert.match(y.exaQuery,/2026-11-04/);
assert.match(y.independentQuery,/independent journalists/);
assert.match(y.independentQuery,/2026-11-04/);
assert.doesNotMatch(y.independentQuery,/site:|reuters\.com|includeDomains/);
assert.equal(buildWorldNewsDiscoveryPlan("Știri despre Oradea").independentQuery,null);
const english=buildWorldNewsDiscoveryPlan("What major events happened yesterday worldwide?");
assert.equal(english.broadWorld,true);
assert.equal(buildWorldNewsDiscoveryPlan("Știri geopolitice internaționale").broadWorld,true);
assert.equal(buildWorldNewsDiscoveryPlan("Știri despre Oradea").broadWorld,false);
assert.equal(buildWorldNewsDiscoveryPlan("Care este salariul mediu în Dubai?").broadWorld,false);
assert.equal(buildWorldNewsDiscoveryPlan("Explică-mi o rețetă tradițională").broadWorld,false);
const inputs=[...Array.from({length:10},(_,i)=>({url:"https://example.com/"+i,title:"Example "+i})),...Array.from({length:5},(_,i)=>({url:"https://reuters.com/world/"+i,title:"Reuters "+i})),{url:"https://apnews.com/article/new",title:"AP"}];
const picked=selectNewsPublisherDiverseSources(inputs,{max:12,firstPassPerPublisher:2});
assert.equal(picked.length,12);assert.ok(picked.some(x=>x.url.includes("reuters.com/")));assert.ok(picked.some(x=>x.url.includes("apnews.com/")));
const stats=describeNewsPublishers(picked);
assert.equal(stats.reuters_article_found,true);assert.equal(stats.unique_publisher_count,3);
assert.equal(describeNewsPublishers([]).reuters_article_found,false);
console.log("PASS balanced world news discovery and source diversity planning");
