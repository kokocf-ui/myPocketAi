import assert from 'node:assert/strict';
import {assistantPreferredName as name,assistantIdentityInstruction} from './assistant_personal_identity.mjs';
import {weatherPracticalAdvice as advice,weatherLocalityLabel} from './weather_practical_advice.mjs';
const history=[{role:'assistant',content:'Sunt pregătită să aflu despre tine, Costi. Cum îți poți spune?'}];
assert.equal(name('Cum vrei tu, dar Costi, cred că este perfect',history),'Costi');
assert.equal(name('Costi',history),'Costi');assert.equal(name('Mă cheamă Costi'),'Costi');assert.equal(name('Îmi poți spune Costi'),'Costi');assert.equal(name('Numele meu este Ana Maria'),'Ana Maria');
for(const t of ['Cine este Costi Ioniță?','Caută informații despre Costi','Spune-mi un banc','Spune-mi vremea azi','Spune-mi Vremea','Spune-mi cum ajung la gară','Cum ajung la Costi?','Call me a taxi'])assert.equal(name(t),null,t);
assert.match(assistantIdentityInstruction(),/Never identify them as a celebrity/);
assert.equal(weatherLocalityLabel({town:'Grays',suburb:'South Stifford'}),'Grays');
const row={temperature:22,feels_like:22,precipitation_mm:0,precipitation_probability:0,weather_code:0,wind_kmh:10};
assert.deepEqual(advice([row]),[]);
assert.match(advice([{...row,temperature:9,feels_like:9}]).join(' '),/jachetă/);
assert.match(advice([{...row,temperature:2,feels_like:0.5}]).join(' '),/haină groasă/);
assert.match(advice([{...row,precipitation_mm:2,weather_code:61}]).join(' '),/umbrelă/);
assert.match(advice([{...row,precipitation_probability:80}]).join(' '),/umbrelă/);
assert.doesNotMatch(advice([{...row,precipitation_probability:30}]).join(' '),/umbrelă/);
assert.match(advice([{...row,weather_code:73,temperature:-1,feels_like:-2}]).join(' '),/ninsori/);
assert.match(advice([{...row,precipitation_mm:2,wind_kmh:50}]).join(' '),/impermeabilă/);
assert.match(advice([{...row,temperature:31,feels_like:32}]).join(' '),/ia apă/);
assert.deepEqual(advice([]),[]);
console.log('PASS preferred-name speech acts never imply public identity; city-only locality and condition-dependent coat/jacket/umbrella/snow/heat advice.');
