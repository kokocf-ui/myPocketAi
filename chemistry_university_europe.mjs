export const CHEMISTRY_EHEA_REFERENCE='https://education.ec.europa.eu/eu/education-levels/higher-education/inclusive-and-connected-higher-education/european-credit-transfer-and-accumulation-system';
export function chemistryUniversityRoutes(country){
 const code=String(country||'').toUpperCase();
 if(!Object.prototype.hasOwnProperty.call(CHEMISTRY_UNIVERSITY_PROFILES,code))return [];
 const p=CHEMISTRY_UNIVERSITY_PROFILES[code];
 const r=[];
 const material=(id,years,ro,en,source,verified)=>({id,years,ro,en,source,verified,
  noticeRo:verified?'Exemplu real al unei universități; cursurile Educației sunt materiale originale orientative, NU planul acreditat al instituției.':
   'Model educațional de comparație; durata nu este confirmată pentru această țară sau universitate.',
  noticeEn:verified?'Real institution example; the lessons in Education are original advisory materials, NOT the institution’s accredited course plan.':
   'Educational comparison model; this duration is not verified for the country or institution.'});
 if(p.example)r.push(material('example-'+p.example.years,p.example.years,
  p.example.years+' ani · '+p.example.ro,p.example.years+' years · '+p.example.en,p.example.source,true));
 for(const t of p.special)r.push(material('integrated-'+t.years,t.years,
  t.years+' ani · '+t.ro,t.years+' years · '+t.en,t.source,true));
 for(const years of [3,4])if(!r.some(x=>x.years===years))r.push(material('advisory-'+years,years,
  years+' ani · parcurs orientativ'+(code.startsWith('GB-')?'':' · '+(years*60)+' ECTS model'),
  years+' years · advisory route'+(code.startsWith('GB-')?'':' · '+(years*60)+' ECTS model'),
  CHEMISTRY_EHEA_REFERENCE,false));
 return r;
}
export function chemistryUniversityRoute(country,id){
 const routes=chemistryUniversityRoutes(country);
 return routes.find(x=>x.id===id)||routes[0]||null;
}
export function chemistryUniversityYears(country,routeId){
 const route=chemistryUniversityRoute(country,routeId);
 if(!route)return [];
 return Array.from({length:route.years},(_,i)=>({id:'univ-'+(i+1),
  ro:'Anul universitar '+(i+1),en:'University year '+(i+1),
  year:i+1,routeId:route.id}));
}
