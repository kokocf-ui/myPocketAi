import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const mixed=readFileSync(new URL('./one_field_journey_ui.mjs',import.meta.url),'utf8');
const national=readFileSync(new URL('./national_public_transport_ui.mjs',import.meta.url),'utf8');
const backend=readFileSync(new URL('./backend.js',import.meta.url),'utf8');
const helperStart=mixed.indexOf('function createTransportDepartureStep(');
const helperEnd=mixed.indexOf('function showOneFieldJourney(',helperStart);
assert.ok(helperStart>=0&&helperEnd>helperStart,'Shared calendar helper is part of the existing Maps UI script');
const helper=mixed.slice(helperStart,helperEnd);
assert.ok(helper.includes("picker.type='datetime-local'"),'Android native date/time picker');
assert.ok(helper.includes("picker.value=formatLocal(new Date())"),'Picker prefilled with the phone local current time');
assert.ok(helper.includes("let changed=false"),'Calendar is optional');
assert.ok(helper.includes("departureAt=null"),'Unchanged calendar uses backend request time');
assert.ok(helper.includes("if(changed)"),'An edited calendar date becomes explicit');
assert.ok(helper.includes("departureAt=date.toISOString()"),'Chosen local datetime is transmitted as an exact timestamp');
assert.ok(helper.includes("date.getTime()<Date.now()-120000"),'Prevent dates in the past');
assert.ok(helper.includes("onBack?.()"),'Calendar can return to the previous step');
const mixMode=mixed.slice(mixed.indexOf("const runMode=async(mode)=>{"),mixed.indexOf('const showModes=()=>{'));
assert.ok(mixMode.includes("if(mode==='transit'){"),'Calendar is for mixed transport only');
assert.ok(mixMode.includes('createTransportDepartureStep('));
assert.ok(mixMode.includes('transitDepartureAt:departureAt'));
assert.ok(mixMode.indexOf("if(mode==='transit'){")<mixMode.indexOf("state.pendingTravelMode=mode"),'Driving path bypasses the calendar');
const nationalAction=national.slice(national.indexOf("const go=createButton(t('search')"),national.indexOf('});go.disabled=true;',national.indexOf("const go=createButton(t('search')"))+20);
assert.ok(nationalAction.includes('createTransportDepartureStep('));
assert.ok(nationalAction.includes('transitDepartureAt:departureAt'));
assert.ok(nationalAction.includes('nationalPublicTransport:true'));
assert.ok(national.includes("journey_suggest:{query,country_code:country,location:origin}"),'Domestic boundary remains unchanged');
assert.ok(backend.includes('transit_departure_at'),'Backend already accepts scheduled departures');
console.log('PASS departure calendar for national transit and mixed mode, direct driving unchanged');
