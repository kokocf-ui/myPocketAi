import assert from 'node:assert/strict';
import vm from 'node:vm';
import frontend from './index.js';
import {THEORY_ENTRIES,searchTheory} from './education_theory.mjs';
const html=await(await frontend.fetch(new Request('https://math-theory-check.test/'))).text();
const script=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script,'frontend inline script exists');
new vm.Script(script);
assert.match(script,/function educationTheoryOpen\(subject,level\)/);
assert.match(script,/function educationTheoryFind\(query,subject,level,limit=4\)/);
assert.match(script,/educationTheoryOpen\('math',mathJourney.level\)/);
assert.match(script,/theory.onclick=\(\)=>physicsTheoryOpen\(\)/,'Physics opens its own chapter theory from workspace');
assert.match(script,/chemistryCurriculumPreset=\{level:scienceJourney.level,topic:scienceJourney.topic\}/,'Chemistry theory opens in the selected topic');
assert.match(script,/educationTheoryHandleAndroid\(data\)/);
assert.match(script,/if\(document.getElementById\('educationTheoryDialog'\)\?\.open\)/);
assert.match(script,/mode:'theory'/);
assert.match(html,/education-theory-dialog \[hidden\]\{display:none!important\}/);
assert.doesNotMatch(script,/webkitSpeechRecognition|window\.SpeechRecognition/,'only Android voice capture in APK');
const begin=script.indexOf('const EDUCATION_THEORY_DATA=');
const end=script.indexOf('function educationTheoryStopVoice()',begin);
assert.ok(begin>0&&end>begin,'one embedded catalog and indexed search');
const api=vm.runInNewContext(script.slice(begin,end)+'\n({find:educationTheoryFind,entries:EDUCATION_THEORY_DATA})');
assert.equal(api.entries.length,THEORY_ENTRIES.length);
assert.equal(api.find('', 'math','advanced',4).length,0,'no suggestions before first keystroke');
assert.equal(api.find('p','math','advanced',4).length,4,'first-character lookup capped to 4');
assert.equal(api.find('PITAG','math','beginner',4)[0].title,'Pitagora');
assert.equal(api.find('thale','math','beginner',4)[0].title,'Teorema lui Thales');
assert.equal(api.find('oh','physics',null,4)[0].title,'Legea lui Ohm');
assert.equal(api.find('green','math','intermediate',4).length,0);
assert.equal(api.find('green','math','advanced',4)[0].title,'Teorema lui Green');
assert.equal(searchTheory('lavoisier',{subject:'chemistry'})[0].title,'Legea conservării masei');
console.log('PASS integrated theory UI: modal, Android voice, progressive first-letter search, zero default cards, levels');
