import assert from 'node:assert/strict';
import vm from 'node:vm';
import frontend from './index.js';
const html=await(await frontend.fetch(new Request('https://fixture/'))).text();
const script=[...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)][0]?.[1];
assert.ok(script,'embedded math script exists');
new vm.Script(script);
const start=script.indexOf('function mathLinearSystem(');
const end=script.indexOf('function mathAlgebraEngines(',start);
assert.ok(start>0&&end>start,'system engine is registered');
const api=vm.runInNewContext(script.slice(start,end)+'\n({parse:mathLinearSystem,solve:mathLinearSystemSolution,method:mathLinearSystemMethod,graph:mathLinearSystemGraphData})',
 {state:{language:'ro'},learningLabel:(ro,en)=>ro,mathLinearNotation:()=>({number:n=>String(n).replace('-', '−')})});
const input='2x+3y=13\n3x-y=3';
const model=api.parse(input);
assert.ok(model,'two-line system recognized');
assert.equal(model.kind,'unique');
assert.equal(model.det,-11);
assert.ok(Math.abs(model.x-2)<1e-10);
assert.ok(Math.abs(model.y-3)<1e-10);
const result=api.solve(input);
assert.equal(result.steps.length,4);
assert.equal(result.steps[3].verificationSteps.length,2);
assert.match(result.conclusion,/x = 2, y = 3/);
assert.equal(api.graph(input).system.kind,'unique');
assert.ok(api.method(input).rules.length>=4);
assert.equal(api.parse('x+y=2\n2x+2y=4').kind,'dependent');
assert.equal(api.parse('x+y=2\nx+y=3').kind,'inconsistent');
assert.equal(api.parse('x^2+y=2\nx+y=3'),null);
assert.equal(api.parse('x+y=2'),null);
assert.equal(api.parse('x+y=2\nx+y=3\nx-y=1'),null);
assert.equal(api.parse('x*y=2\nx+y=3'),null);
assert.ok(script.includes("id:'linear-system-2x2'"));
assert.ok(script.includes("mathLinearSystemFigure(equationGraph.system)"));
console.log('PASS 2x2 systems: unique/dependent/inconsistent, verified roots and graph routing');
