import assert from 'node:assert/strict';
import vm from 'node:vm';
import frontend from './index.js';
const html=await(await frontend.fetch(new Request('https://math.test/'))).text();
const script=[...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)][0]?.[1];
assert.ok(script,'frontend script');
new vm.Script(script);
const from=script.indexOf('function mathPlaneShapeModel(');
const to=script.indexOf('function mathPlaneNumber(',from);
assert.ok(from>=0&&to>from,'geometry model function');
const model=vm.runInNewContext(script.slice(from,to)+'\nmathPlaneShapeModel', {});
const exercise='Un dreptunghi ABCD are lungimea AB de 8 cm și lățimea BC de 5 cm. Calculează aria și perimetrul dreptunghiului. Reprezintă grafic figura și marchează vârfurile A, B, C și D.';
const shape=model(exercise);
assert.ok(shape,'recognize labeled sides AB and BC');
assert.equal(shape.kind,'rectangle');
assert.equal(shape.a,8);assert.equal(shape.b,5);
assert.equal(shape.unit,'cm');
assert.equal(shape.area,40);assert.equal(shape.perimeter,26);
assert.equal(model('Un dreptunghi are lungimea de 8 cm și lățimea de 5 cm.').area,40,'preserve unlabelled cases');
assert.ok(script.includes("if(verifiedShape)return mathPlaneShapeFigure(verifiedShape);"),'render diagram from verified model');
assert.ok(script.includes("mathSvgText(svg,x-9,y-8,'A'"),'label rectangle A');
assert.ok(script.includes("mathSvgText(svg,x+w+9,y+h+14,'C'"),'label rectangle C');
assert.ok(script.includes("'AB'")&&script.includes("'BC'"),'length labels provided');
console.log('PASS text-only geometry T2: 8×5 cm, labels ABCD, area 40, perimeter 26');
