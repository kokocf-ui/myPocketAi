import assert from 'node:assert/strict';
import vm from 'node:vm';
import frontend from './index.js';
const html=await(await frontend.fetch(new Request('https://math-input-contract.test/'))).text();
const script=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script);
new vm.Script(script);
const a=script.indexOf('function educationMathOcrIncomplete(');
const b=script.indexOf('// Dedicated Math results are independent',a);
assert.ok(a>0&&b>a);
const incomplete=vm.runInNewContext(script.slice(a,b)+'\neducationMathOcrIncomplete');
for(const valid of ['2+3','x+y=z','(2+3)*4','(-1)+2','2*[3+4]','√(9)+1','{2+[3*(4+1)]}'])assert.equal(incomplete(valid),false,'valid: '+valid);
for(const invalid of ['','2+','(2+3','2+[3+4','2+[3+4)','√+2','2=','2+3}'])assert.equal(incomplete(invalid),true,'invalid: '+invalid);
const repairStart=script.indexOf('function mathPhotoOcrApplyCorrection(');
const repairEnd=script.indexOf('function mathPhotoOcrRisk(source)',repairStart);
const repair=vm.runInNewContext(script.slice(repairStart,repairEnd)+'\nmathPhotoOcrApplyCorrection');
assert.equal(repair('2V 5 + 4V9','radical'),'2√5 + 4√9');
assert.equal(repair('2V5 - 3V5','radical'),'2√5 - 3√5');
assert.equal(repair('2V5 - 3V5','none'),'2V5 - 3V5');
const parseA=script.indexOf('function mathPhotoCandidates(');
const parseB=script.indexOf('// Educational mathematics: reject obvious OCR fragments',parseA);
const parse=vm.runInNewContext(script.slice(parseA,parseB)+'\nmathPhotoCandidates');
const formulae=Array.from({length:24},(_,i)=>(i+1)+'. '+(i+2)+'x + '+(i+1)+' = '+(i+3)).join('\n');
assert.equal(parse(formulae).length,24,'OCR does not show only three items');
assert.ok(script.includes('mathPhotoNeedsReview=true;'));
assert.ok(script.includes('if(mathPhotoOcrRisk(candidate))'),'OCR symbol ambiguity requires review');
assert.ok(script.includes('mathVoiceChooseTranscript('),'voice negative-number alternative check stays active');
console.log('PASS mathematical image/voice input: 7 valid, 8 malformed, radical confirmation and 24 exercises');
