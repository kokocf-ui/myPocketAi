import assert from 'node:assert/strict';
import {buildOmioAffiliateUrl,omioAffiliateReady} from './omio_affiliate.mjs';

const base={impactPartnerId:'123456',mobileAppApproved:true,departure:'London',arrival:'Paris',departureDate:'2026-12-15'};
assert.equal(omioAffiliateReady({...base,mobileAppApproved:false}),false);
assert.equal(buildOmioAffiliateUrl({...base,mobileAppApproved:false}),null);
assert.equal(buildOmioAffiliateUrl({...base,impactPartnerId:''}),null);
assert.equal(buildOmioAffiliateUrl({...base,departure:''}),null);
assert.equal(buildOmioAffiliateUrl({...base,departure:'51.50,-0.1\n'}),null);
assert.equal(buildOmioAffiliateUrl({...base,departureDate:'2026-02-30'}),null);
assert.equal(buildOmioAffiliateUrl({...base,returnDate:'2026-12-10'}),null);
assert.equal(buildOmioAffiliateUrl({...base,travelMode:'walking'}),null);
const output=buildOmioAffiliateUrl({...base,travelMode:'TRAIN',locale:'ro',currency:'RON',returnDate:'2026-12-20'});
const link=new URL(output);
assert.equal(link.hostname,'omio.sjv.io');
assert.equal(link.pathname,'/c/123456/4057579/7385');
const target=new URL(link.searchParams.get('u'));
assert.equal(target.hostname,'www.omio.com');
assert.equal(target.pathname,'/links/626fa8a9-f982-43d0-ace9-9a13f6b14612');
assert.equal(target.searchParams.get('departurePosTerm'),'London');
assert.equal(target.searchParams.get('arrivalPosTerm'),'Paris');
assert.equal(target.searchParams.get('departureDate'),'2026-12-15');
assert.equal(target.searchParams.get('returnDate'),'2026-12-20');
assert.equal(target.searchParams.get('travelMode'),'TRAIN');
assert.equal(target.searchParams.get('locale'),'ro');
assert.equal(target.searchParams.get('currency'),'RON');
const special=buildOmioAffiliateUrl({...base,departure:'Cluj-Napoca',arrival:'Brașov & Centru'});
assert.equal(new URL(new URL(special).searchParams.get('u')).searchParams.get('arrivalPosTerm'),'Brașov & Centru');
console.log('PASS Omio: approval gate, Impact attribution, dates, modes, encoding');
