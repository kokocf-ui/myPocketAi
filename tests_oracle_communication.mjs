const {subtle,getRandomValues}=webcrypto;
const a=await subtle.generateKey({name:'ECDH',namedCurve:'P-256'},false,['deriveKey']);
const b=await subtle.generateKey({name:'ECDH',namedCurve:'P-256'},false,['deriveKey']);
const pubA=await subtle.importKey('jwk',await subtle.exportKey('jwk',a.publicKey),{name:'ECDH',namedCurve:'P-256'},false,[]);
const pubB=await subtle.importKey('jwk',await subtle.exportKey('jwk',b.publicKey),{name:'ECDH',namedCurve:'P-256'},false,[]);
const keyA=await subtle.deriveKey({name:'ECDH',public:pubB},a.privateKey,{name:'AES-GCM',length:256},false,['encrypt','decrypt']);
const keyB=await subtle.deriveKey({name:'ECDH',public:pubA},b.privateKey,{name:'AES-GCM',length:256},false,['encrypt','decrypt']);
const iv=webcrypto.getRandomValues(new Uint8Array(12)),data=new TextEncoder().encode('Salut, prietene!');
const aad=new TextEncoder().encode('sender|recipient');
const cipher=await subtle.encrypt({name:'AES-GCM',iv,additionalData:aad},keyA,data);
const decrypted=await subtle.decrypt({name:'AES-GCM',iv,additionalData:aad},keyB,cipher);
assert.equal(new TextDecoder().decode(decrypted),'Salut, prietene!');
