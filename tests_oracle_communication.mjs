const a=await crypto.subtle.generateKey({name:'ECDH',namedCurve:'P-256'},false,['deriveKey']);
const b=await crypto.subtle.generateKey({name:'ECDH',namedCurve:'P-256'},false,['deriveKey']);
const ap=await crypto.subtle.importKey('jwk',await crypto.subtle.exportKey('jwk',a.publicKey),{name:'ECDH',namedCurve:'P-256'},false,[]);
const bp=await crypto.subtle.importKey('jwk',await crypto.subtle.exportKey('jwk',b.publicKey),{name:'ECDH',namedCurve:'P-256'},false,[]);
const ak=await crypto.subtle.deriveKey({name:'ECDH',public:bp},a.privateKey,{name:'AES-GCM',length:256},false,['encrypt','decrypt']);
const bk=await crypto.subtle.deriveKey({name:'ECDH',public:ap},b.privateKey,{name:'AES-GCM',length:256},false,['encrypt','decrypt']);
const iv=crypto.getRandomValues(new Uint8Array(12));
const plain=new TextEncoder().encode('Salut, familie!');
const aad=new TextEncoder().encode('sender|recipient');
const cipher=await crypto.subtle.encrypt({name:'AES-GCM',iv,additionalData:aad},ak,plain);
const out=await crypto.subtle.decrypt({name:'AES-GCM',iv,additionalData:aad},bk,cipher);
assert.equal(new TextDecoder().decode(out),'Salut, familie!');
