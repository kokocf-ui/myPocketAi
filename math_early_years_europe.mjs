export function mathEarlyYearEntries({country,grade,topic}={}){
 const code=String(country||'').toUpperCase(),year=String(grade||'');
 const first=(code==='NL'&&year==='G1')||(code==='IE'&&year==='JI');
 const second=(code==='NL'&&year==='G2')||(code==='IE'&&year==='SI');
 if(!first&&!second)return null;
 const stage=first?'first':'second';
 return (MATH_EARLY_YEAR_BANK[stage]?.[topic]||[]).map((row,i)=>({
  id:'math-early-'+code.toLowerCase()+'-'+year.toLowerCase()+'-'+topic+'-'+(i+1),
  subject:'math',level:'beginner',stage:'primary',phase:first?1:2,topic,
  country:code,grade:year,title:row[0],enTitle:row[1],
  statement:row[2],formula:row[3],worked:row[4],practice:row[5],answers:row[6],
  sourceStatus:'age-appropriate-advisory',aliases:[]
 }));
}
